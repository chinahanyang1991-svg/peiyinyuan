"""
Office 文档解析器
使用 python-docx 和 python-pptx 原生解析 Office 文档
"""

import re
from pathlib import Path
from typing import Optional

# ----------------------------------------------------------------------
# WF-14: 元数据回退链
#   落盘文件名已经是 UUID（backend 以 book_id 重命名保存），
#   旧实现 `metadata.get("title", Path(file_path).stem)` 于是把 UUID 当成书名
#   写进库里，书籍列表/成品文件名/m4b 元数据全都显示 UUID；
#   python-docx 生成的文档 core.author 还固定是 "python-docx"。
# ----------------------------------------------------------------------

_UUID_RE = re.compile(
    r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$", re.IGNORECASE)

# 工具/模板写死的占位作者名（不是真实作者，展示出来只会误导用户）
_PLACEHOLDER_AUTHORS = {
    "python-docx", "python_docx", "python-pptx", "python pptx",
    "open xml sdk", "openxmlsdktm", "document", "author", "unknown",
    "un-named", "unnamed", "未知", "作者", "佚名",
    "microsoft office user", "microsoft word", "microsoft office",
}

# 看起来像"章节标题"而非"书名"的段落
_CHAPTER_HEADING_RE = re.compile(
    r"^\s*(第\s*[0-9零〇一二三四五六七八九十百千万两]+\s*[章节回卷篇部集]"
    r"|chapter\s+[0-9IVXLCDM]+"
    r"|part\s+[0-9IVXLCDM]+"
    r"|volume\s+[0-9IVXLCDM]+"
    r"|序\s*[章言节]?|前\s*言|后\s*记|目\s*录|附\s*录|结\s*语|尾声|楔\s*子)",
    re.IGNORECASE)


def is_placeholder_value(value: str) -> bool:
    """判断 core properties 里的作者/标题是不是工具默认值。"""
    v = (value or "").strip()
    if not v:
        return True
    if "generated by" in v.lower():
        return True
    return v.casefold().replace(" ", "-") in _PLACEHOLDER_AUTHORS


def looks_like_uuid(name: str) -> bool:
    return bool(_UUID_RE.match((name or "").strip()))


def clean_author(value: str) -> str:
    """工具默认作者 -> 空串，交给上层留空而不是显示 python-docx。"""
    v = (value or "").strip()
    return "" if is_placeholder_value(v) else v


def is_title_style(style_name: str) -> bool:
    """样式是否是"书名/标题"级（Title），而不是 Subtitle 或中文的"标题 1"(=Heading 1)。"""
    s = (style_name or "").strip().casefold()
    if not s:
        return False
    if re.match(r"^(标题|书名)$", s):
        return True
    return "title" in [t for t in re.split(r"[^a-z0-9]+", s) if t]


def is_chapter_heading(text: str) -> bool:
    return bool(_CHAPTER_HEADING_RE.match((text or "").strip()))


def resolve_docx_title(paragraphs: list, core_title: str = "",
                       original_name: str = "", stored_stem: str = "") -> str:
    """按「core 属性标题 -> 文档 Title 段 -> 首个 Heading -> 第一段 -> 原始文件名 -> 落盘名」回退。

    paragraphs: OfficeParser.parse_docx 产出的 [{"text","style","level"}, ...]
    original_name: 上传时的原始文件名（拿不到就留空，此时至少保证不返回 UUID）
    stored_stem: 落盘文件名 stem（通常是 UUID，只在其它都拿不到时兜底）
    """
    def _ok(v: str, max_len: int = 60) -> str:
        v = (v or "").strip()
        if not v or is_placeholder_value(v) or looks_like_uuid(v):
            return ""
        return v[:max_len]

    # 1) 文档核心属性里的人工标题
    t = _ok(core_title)
    if t:
        return t

    # 2) Title/标题 样式段（书名页）
    for p in paragraphs or []:
        if is_title_style(p.get("style", "")):
            t = _ok(p.get("text", ""))
            if t:
                return t

    # 3) 首个 Heading（不含"第一章"这类章题，避免把章名当书名）
    for p in paragraphs or []:
        if (p.get("level") or 0) > 0:
            text = (p.get("text") or "").strip()
            if text and not is_chapter_heading(text):
                t = _ok(text)
                if t:
                    return t
            break

    # 4) 第一段正文（短且不是章题才敢当书名）
    for p in paragraphs or []:
        text = (p.get("text") or "").strip()
        if not text:
            continue
        if not is_chapter_heading(text) and len(text) <= 30:
            t = _ok(text)
            if t:
                return t
        break

    # 5) 上传原始文件名 stem
    stem = Path(original_name or "").stem.strip()
    if stem and not is_placeholder_value(stem):
        return stem

    # 6) 落盘名：非 UUID 时可用；是 UUID 时留空
    #    （backend 的 import_book 用 `book_data.title or Path(file.filename).stem`
    #      兜底，留空反而能让用户上传的真实文件名生效，比把 UUID 写进书名好）
    stored = (stored_stem or "").strip()
    if stored and not looks_like_uuid(stored) and not is_placeholder_value(stored):
        return stored
    return ""


class OfficeParser:
    """
    Office 文档解析器
    支持 DOCX、PPTX 格式的文本提取

    用法:
        result = OfficeParser.parse_docx("file.docx")
        result = OfficeParser.parse_pptx("file.pptx")
    """

    @staticmethod
    def parse_docx(file_path: str, original_name: str = "") -> dict:
        """
        解析 DOCX 文件，提取文本结构和元数据

        Args:
            file_path: 落盘路径（导入链路里通常是 UUID 文件名）
            original_name: 用户上传时的原始文件名，能拿到就传，用于书名兜底

        返回:
        {
            "title": str,
            "paragraphs": [{"text": str, "style": str, "level": int}, ...],
            "full_text": str,
            "metadata": {"author": str, "created": str, ...},
        }
        """
        stored_stem = Path(file_path).stem

        def _fallback_result(error: str, extra: Optional[dict] = None) -> dict:
            res = {
                "title": resolve_docx_title([], "", original_name, stored_stem),
                "paragraphs": [],
                "full_text": "",
                "metadata": {},
                "error": error,
            }
            if extra:
                res.update(extra)
            return res

        try:
            from docx import Document
        except ImportError:
            return _fallback_result("请安装 python-docx: pip install python-docx")

        try:
            doc = Document(file_path)
        except Exception as e:
            return _fallback_result(f"DOCX 解析失败: {e}")

        # 提取元数据（工具默认值不采信，见 WF-14）
        metadata = {}
        core_title = ""
        try:
            props = doc.core_properties
            if props.title and not is_placeholder_value(props.title):
                core_title = props.title.strip()
                metadata["title"] = core_title
            author = clean_author(props.author)
            if not author:
                # python-docx 之类工具写的 author 是占位值，退回"最后修改者"
                author = clean_author(getattr(props, "last_modified_by", ""))
            if author:
                metadata["author"] = author
            if props.created:
                metadata["created"] = str(props.created)
            if props.modified:
                metadata["modified"] = str(props.modified)
            if props.subject:
                metadata["subject"] = props.subject
        except Exception:
            pass

        # 提取段落（保留层次结构）
        paragraphs = []
        for para in doc.paragraphs:
            text = para.text.strip()
            if not text:
                continue
            style_name = para.style.name if para.style else "Normal"
            # 推断标题级别
            level = 0
            if "Heading" in style_name or "heading" in style_name:
                try:
                    level = int(style_name.replace("Heading ", "").replace("heading ", ""))
                except ValueError:
                    level = 1

            paragraphs.append({
                "text": text,
                "style": style_name,
                "level": level,
            })

        # 提取表格中的文本
        for table in doc.tables:
            for row in table.rows:
                row_texts = []
                for cell in row.cells:
                    cell_text = cell.text.strip()
                    if cell_text:
                        row_texts.append(cell_text)
                if row_texts:
                    paragraphs.append({
                        "text": " | ".join(row_texts),
                        "style": "Table",
                        "level": 0,
                    })

        # WF-14: 书名回退链 —— 核心属性 -> Title 段 -> 首个 Heading -> 第一段
        #          -> 原始文件名 -> 落盘名（UUID 只作最后兜底）
        title = resolve_docx_title(paragraphs, core_title, original_name, stored_stem)
        metadata["title"] = title

        full_text = "\n\n".join(p["text"] for p in paragraphs)

        return {
            "title": title,
            "paragraphs": paragraphs,
            "full_text": full_text,
            "metadata": metadata,
        }

    @staticmethod
    def parse_pptx(file_path: str) -> dict:
        """
        解析 PPTX 文件，提取幻灯片文本

        返回:
        {
            "title": str,
            "slides": [{"slide_num": int, "texts": [str], "notes": str}, ...],
            "full_text": str,
        }
        """
        try:
            from pptx import Presentation
        except ImportError:
            return {
                "title": Path(file_path).stem,
                "slides": [],
                "full_text": "",
                "error": "请安装 python-pptx: pip install python-pptx",
            }

        try:
            prs = Presentation(file_path)
        except Exception as e:
            return {
                "title": Path(file_path).stem,
                "slides": [],
                "full_text": "",
                "error": f"PPTX 解析失败: {e}",
            }

        slides = []
        for slide_num, slide in enumerate(prs.slides, 1):
            texts = []
            for shape in slide.shapes:
                if shape.has_text_frame:
                    for para in shape.text_frame.paragraphs:
                        t = para.text.strip()
                        if t:
                            texts.append(t)
                if shape.has_table:
                    table = shape.table
                    for row in table.rows:
                        row_texts = [cell.text.strip() for cell in row.cells if cell.text.strip()]
                        if row_texts:
                            texts.append(" | ".join(row_texts))

            notes = ""
            if slide.has_notes_slide:
                notes_text = slide.notes_slide.notes_text_frame.text.strip()
                if notes_text:
                    notes = notes_text

            slides.append({
                "slide_num": slide_num,
                "texts": texts,
                "notes": notes,
            })

        full_text = "\n\n".join(
            "\n".join(s["texts"]) for s in slides if s["texts"]
        )

        return {
            "title": Path(file_path).stem,
            "slides": slides,
            "full_text": full_text,
        }

    @staticmethod
    def get_docx_chapters(file_path: str, original_name: str = "",
                          parsed: Optional[dict] = None) -> list:
        """
        从 DOCX 文件提取章节结构（基于 Heading 样式）

        返回:
        [{"title": str, "level": int, "content": str, "index": int}, ...]
        """
        result = parsed if parsed is not None else OfficeParser.parse_docx(
            file_path, original_name=original_name)
        if "error" in result:
            return []

        chapters = []
        current_chapter = None
        current_content = []

        for para in result["paragraphs"]:
            if para["level"] > 0:
                # 保存上一章
                if current_chapter is not None:
                    chapters.append({
                        "title": current_chapter,
                        "level": para["level"],
                        "content": "\n\n".join(current_content),
                        "index": len(chapters),
                        "char_count": sum(len(c) for c in current_content),
                    })
                current_chapter = para["text"]
                current_content = []
            else:
                current_content.append(para["text"])

        # 保存最后一章
        if current_chapter is not None and current_content:
            chapters.append({
                "title": current_chapter,
                "level": 1,
                "content": "\n\n".join(current_content),
                "index": len(chapters),
                "char_count": sum(len(c) for c in current_content),
            })

        # 如果没有标题分段，整篇作为一个章节
        if not chapters and result["full_text"]:
            chapters.append({
                "title": result["title"],
                "level": 0,
                "content": result["full_text"],
                "index": 0,
                "char_count": len(result["full_text"]),
            })

        return chapters